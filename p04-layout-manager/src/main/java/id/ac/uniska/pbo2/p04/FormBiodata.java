    private void simpanButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_simpanButtonActionPerformed

        String nama = namaField.getText().trim();
        String npm = npmField.getText().trim();
        String prodi = String.valueOf(prodiComboBox.getSelectedItem());
        String semester = String.valueOf(semesterSpinner.getValue());
        String email = emailField.getText().trim();
        String hp = hpField.getText().trim();
        String alamat = alamatArea.getText().trim();

        if (nama.isEmpty() || npm.isEmpty()
                || email.isEmpty() || hp.isEmpty()
                || alamat.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Mohon lengkapi semua data terlebih dahulu!",
                    "Data Belum Lengkap",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        String pesan = "BIODATA MAHASISWA\n\n"
                + "Nama Lengkap : " + nama + "\n"
                + "NPM          : " + npm + "\n"
                + "Program Studi: " + prodi + "\n"
                + "Semester     : " + semester + "\n"
                + "Email        : " + email + "\n"
                + "Nomor HP     : " + hp + "\n"
                + "Alamat       : " + alamat;

        javax.swing.JOptionPane.showMessageDialog(
                this,
                pesan,
                "Biodata Berhasil Disimpan",
                javax.swing.JOptionPane.INFORMATION_MESSAGE
        );

    }//GEN-LAST:event_simpanButtonActionPerformed

